// ─── Helpers ─────────────────────────────────────────────────────

function buildCodeSystemPrompt(): string {
  const tools = toolRegistry.listToolsForMode('code');
  // Compact format: name + first 250 chars of description (same as work-mode experiments)
  const toolDescriptions = tools
    .map((t) => `### ${t.name}\n${t.description}`)
    .join('\n\n---\n\n');

  return `You are an AI assistant that helps users by selecting and calling the right tool.

You have access to the following tools (mode: code — software development, building projects):

${toolDescriptions}

---

## Your Task

Given a user's message, decide which SINGLE tool best matches their intent, and provide the arguments to call it.

## Response Format

You MUST respond with a strict JSON object — no markdown, no explanation outside the JSON:

\`\`\`json
{
  "tool": "<tool_name>",
  "args": { ... },
  "reasoning": "<one sentence explaining why you chose this tool>"
}
\`\`\`

## Rules

1. Pick exactly ONE tool from the list above.
2. Provide ALL required arguments for that tool. Make reasonable assumptions about missing arguments.
3. Common argument requirements:
   - read_file: path (string, e.g. "src/App.tsx", "package.json")
   - list_files: optional filter (string glob like "*.tsx", "src/**")
   - grep: pattern (string) + optional fileGlob + optional caseSensitive + optional maxResults
   - run_shell: command (string like "npm install", "npm run build") + optional timeoutMs
   - screenshot: optional url (default http://localhost:5173) + optional width/height + optional fullPage
   - read_sandbox_file: path (string, can be "dist/index.html", "node_modules/react/package.json")
   - web_search: query (string)
   - read_url: url (string)

## Examples

User: "Read the App.tsx file from the project"
Response: {"tool": "read_file", "args": {"path": "src/App.tsx"}, "reasoning": "User wants to read a project file"}

User: "Run npm install in the sandbox"
Response: {"tool": "run_shell", "args": {"command": "npm install"}, "reasoning": "User wants to install deps"}`;
}

function parseLlmResponse(content: string): { tool: string; args: Record<string, any>; reasoning?: string } | null {
  if (!content) return null;

  const fenceMatch = content.match(/```(?:json)?\s*([\s\S]*?)```/);
  const jsonText = fenceMatch ? fenceMatch[1].trim() : content.trim();

  try {
    const parsed = JSON.parse(jsonText);
    if (typeof parsed === 'object' && parsed !== null && typeof parsed.tool === 'string') {
      return { tool: parsed.tool, args: parsed.args ?? {}, reasoning: parsed.reasoning };
    }
  } catch {
    // Fall through
  }

  const jsonMatch = content.match(/\{[\s\S]*\}/);
  if (jsonMatch) {
    try {
      const parsed = JSON.parse(jsonMatch[0]);
      if (typeof parsed.tool === 'string') {
        return { tool: parsed.tool, args: parsed.args ?? {}, reasoning: parsed.reasoning };
      }
    } catch {
      // give up
    }
  }

  return null;
}

let passed = 0;
let failed = 0;
let intentMatches = 0;
const failures: Array<{ name: string; expected: string; actual: string; reason: string }> = [];

async function runExperiment(
  zai: any,
  case_: CodeExperimentCase,
): Promise<{ ok: boolean; reason: string; actualTool?: string; intentMatch?: boolean }> {
  const systemPrompt = buildCodeSystemPrompt();
  const MAX_RETRIES = 3;
  const BASE_DELAY_MS = 5000;
  let lastError = '';

  for (let attempt = 0; attempt < MAX_RETRIES; attempt++) {
    try {
      const response = await zai.chat.completions.create({
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: case_.prompt },
        ],
        stream: false,
        thinking: { type: 'disabled' },
      });

      const content = response.choices?.[0]?.message?.content;
      if (!content) return { ok: false, reason: 'LLM returned empty content' };

      const choice = parseLlmResponse(content);
      if (!choice) {
        return { ok: false, reason: 'Could not parse JSON from LLM response' };
      }

      const intentMatch = choice.tool === case_.expectedTool;
      if (!intentMatch) {
        return {
          ok: false,
          reason: `LLM picked "${choice.tool}" but expected "${case_.expectedTool}"`,
          actualTool: choice.tool,
          intentMatch: false,
        };
      }

      const toolDef = toolRegistry.getToolByName(choice.tool);
      if (!toolDef) {
        return { ok: false, reason: `Tool "${choice.tool}" not in registry`, intentMatch: true };
      }

      const validation = toolDef.inputSchema.safeParse(choice.args);
      if (!validation.success) {
        return {
          ok: false,
          reason: `Args validation failed: ${validation.error.issues.map((i: any) => i.path.join('.') + ': ' + i.message).join('; ')}`,
          actualTool: choice.tool,
          intentMatch: true,
        };
      }

      // All code-mode tests are intentOnly (no files/sandbox in test env)
      return {
        ok: true,
        reason: `Intent match: picked ${choice.tool} with valid args`,
        actualTool: choice.tool,
        intentMatch: true,
      };
    } catch (err: any) {
      const msg = err?.message ?? String(err);
      if (msg.includes('429') && attempt < MAX_RETRIES - 1) {
        const delay = BASE_DELAY_MS * (attempt + 1);
        process.stdout.write(`[rate-limited, waiting ${delay}ms] `);
        await new Promise((r) => setTimeout(r, delay));
        lastError = msg;
        continue;
      }
      return { ok: false, reason: `Exception: ${msg}`, intentMatch: false };
    }
  }

  return { ok: false, reason: `Failed after ${MAX_RETRIES} retries. Last: ${lastError}`, intentMatch: false };
}

// ─── Main ────────────────────────────────────────────────────────

async function main() {
  console.log('\n=========================================');
  console.log('  Code Mode Tool Selection Experiments');
  console.log('  Model: glm-4-plus (via z-ai SDK)');
  console.log('=========================================\n');

  const zai = await ZAI.create();
  console.log(`Running ${EXPERIMENT_CASES.length} experiments...\n`);

  const INTER_EXPERIMENT_DELAY_MS = 5000;

  for (let idx = 0; idx < EXPERIMENT_CASES.length; idx++) {
    const case_ = EXPERIMENT_CASES[idx];

    if (idx > 0) {
      await new Promise((r) => setTimeout(r, INTER_EXPERIMENT_DELAY_MS));
    }

    process.stdout.write(`  [${(idx + 1).toString().padStart(2, ' ')}/${EXPERIMENT_CASES.length}] ${case_.name.padEnd(40)} `);

    const result = await runExperiment(zai, case_);

    if (result.intentMatch) intentMatches++;

    if (result.ok) {
      console.log('\u2713 OK');
      passed++;
    } else {
      console.log('\u2717 FAIL');
      console.log(`      ${result.reason}`);
      if (result.actualTool) {
        console.log(`      Picked: ${result.actualTool} | Expected: ${case_.expectedTool}`);
      }
      failed++;
      failures.push({
        name: case_.name,
        expected: case_.expectedTool,
        actual: result.actualTool ?? '(parse error)',
        reason: result.reason,
      });
    }
  }

  console.log('\n=========================================');
  console.log(`  PASSED:        ${passed}`);
  console.log(`  FAILED:        ${failed}`);
  console.log(`  Total:         ${EXPERIMENT_CASES.length}`);
  console.log(`  Intent match:  ${intentMatches}/${EXPERIMENT_CASES.length} (${Math.round(intentMatches / EXPERIMENT_CASES.length * 100)}%)`);
  console.log('=========================================\n');

  if (failures.length > 0) {
    console.log('Failure breakdown:');
    console.log('------------------');

    const wrongTool = failures.filter((f) => f.actual !== '(parse error)' && f.actual !== f.expected);
    const parseErrors = failures.filter((f) => f.actual === '(parse error)');
    const argsErrors = failures.filter((f) => !f.reason.includes('LLM picked') && !f.reason.includes('parse') && f.actual === f.expected);

    if (wrongTool.length > 0) {
      console.log(`\nWrong tool picked (${wrongTool.length}):`);
      for (const f of wrongTool) {
        console.log(`  - ${f.name}: expected ${f.expected}, got ${f.actual}`);
      }
    }

    if (parseErrors.length > 0) {
      console.log(`\nParse errors (${parseErrors.length}):`);
      for (const f of parseErrors) {
        console.log(`  - ${f.name}: ${f.reason}`);
      }
    }

    if (argsErrors.length > 0) {
      console.log(`\nArgs validation errors (${argsErrors.length}):`);
      for (const f of argsErrors) {
        console.log(`  - ${f.name}: ${f.reason}`);
      }
    }
  }

  console.log('');
}

main().catch((err) => {
  console.error('Experiment runner crashed:', err);
  process.exit(1);
});
