/**
 * Code Mode Tool Selection Experiments — Real LLM Trials
 * ========================================================
 *
 * Tests whether glm-4-plus picks the correct code-mode tool from the
 * registry when given natural-language prompts about code/build tasks.
 *
 * Mode: code (chatMode='build', sidebarMode='code')
 *
 * Available tools in code mode:
 *   - web_search, read_url (universal)
 *   - read_file, list_files, grep (file-map based)
 *   - run_shell, screenshot, read_sandbox_file (sandbox based)
 *
 * Most code-mode tools need either files (read_file, list_files, grep)
 * or a sandbox (run_shell, screenshot, read_sandbox_file). Since we
 * don't have either in the test environment, most tests are intentOnly
 * (verify the LLM picks the right tool with valid args, but don't
 * execute the tool).
 *
 * Run with: pnpm run test:tools:experiments:code
 */

